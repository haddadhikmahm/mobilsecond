// Helper Functions
function getCarById(id) {
    const numId = parseInt(id, 10);
    return carCatalog.find(c => c.id === numId) || carCatalog[0];
}

function formatRupiah(number) {
    return 'Rp ' + Math.round(number).toLocaleString('id-ID');
}

function calculateInstallment(price, dpPercent = 20, tenorMonths = 60, annualInterestRate = 0.08) {
    const dpAmount = price * (dpPercent / 100);
    const loanPrincipal = price - dpAmount;
    const tenorYears = tenorMonths / 12;
    const totalInterest = loanPrincipal * annualInterestRate * tenorYears;
    const totalLoan = loanPrincipal + totalInterest;
    const monthlyPayment = totalLoan / tenorMonths;
    return {
        dpAmount: Math.round(dpAmount),
        loanPrincipal: Math.round(loanPrincipal),
        monthlyPayment: Math.round(monthlyPayment),
        totalInterest: Math.round(totalInterest),
        totalLoan: Math.round(totalLoan)
    };
}

